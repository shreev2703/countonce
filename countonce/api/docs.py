"""Render the app's OpenAPI schema as ``docs/API.md`` (deterministic: no timestamps)."""

from __future__ import annotations

import json
from typing import Any

from fastapi import FastAPI

INTRO = """# CountOnce HTTP API

Generated by `countonce serve-api --write-docs docs/API.md`; do not edit by hand.

- **Auth:** `Authorization: Bearer <key>` or `X-API-Key: <key>` on every route except `/health`,
  `GET /share/{token}` and `POST /auth/exchange` (takes `X-Auth-Secret`; for the web server).
  Create keys with `countonce jobs --db jobs.db apikey create <user>`.
- **Flow:** `POST /jobs` (draft) -> chunked upload (`/uploads`, attach with `job_id`) ->
  `POST /jobs/{id}/submit` -> `GET /jobs/{id}/events` (SSE) -> `GET /jobs/{id}/result`.
- **Idempotency:** send a client UUID in `Idempotency-Key` on `POST /jobs` and
  `POST /jobs/{id}/submit`; a retry returns the original job and never queues twice.
- **Errors:** `{"error": {"code", "message", "tip", "retryable"}}`. 401 unauthenticated, 404 for
  jobs you do not own, 429 (`Retry-After`) when a rate limit is hit. Typed codes map as below.
"""


def render_api_md(app: FastAPI) -> str:
    from countonce.api.app import HTTP_STATUS

    spec: dict[str, Any] = app.openapi()
    lines = [INTRO, "## Error code to HTTP status", "", "| Code | Status |", "|---|---|"]
    for code, status in sorted(HTTP_STATUS.items(), key=lambda kv: kv[0].value):
        lines.append(f"| `{code.value}` | {status} |")
    lines += ["", "## Routes", "", "| Method | Path | Summary |", "|---|---|---|"]
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            lines.append(f"| {method.upper()} | `{path}` | {op.get('summary', '')} |")
    lines += ["", "## OpenAPI spec", "", "```json", json.dumps(spec, indent=2, sort_keys=True)]
    lines += ["```", ""]
    return "\n".join(lines)
