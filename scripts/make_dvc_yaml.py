"""Generate dvc.yaml and params.yaml from the stage graph in synth/dag.py (PLAN §16B.1).

    python scripts/make_dvc_yaml.py            # write dvc.yaml + params.yaml
    python scripts/make_dvc_yaml.py --check    # exit 1 if the committed files differ

params.yaml is the DAG config (configs/dag.yaml over DagConfig defaults), so DVC stages run
``countonce dag run --config params.yaml --only <stage>``. No remote is configured here.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import asdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from synth.dag import STAGE_GRAPH, STAGES, DagConfig  # noqa: E402

HEADER = (
    "# Generated by scripts/make_dvc_yaml.py from synth/dag.py. Do not edit; run `make dvc-yaml`.\n"
)


def build_params(root: Path = ROOT) -> dict:
    params = asdict(DagConfig())
    src = root / "configs" / "dag.yaml"
    if src.exists():
        params.update(yaml.safe_load(src.read_text()) or {})
    DagConfig(**params).check()
    return params


def build_dvc(params: dict) -> dict:
    work = str(params["work_dir"]).rstrip("/")
    stages: dict = {}
    for st in STAGES:
        spec = STAGE_GRAPH[st]
        deps = [f"{work}/{d}" if d in STAGE_GRAPH else d for d in spec["deps"]]
        stage: dict = {
            "cmd": f"countonce dag run --config params.yaml --only {st}",
            "deps": deps,
        }
        if spec["params"]:
            stage["params"] = list(spec["params"])
        stage["outs"] = [f"{work}/{st}", {f"{work}/stamps/{st}.json": {"cache": False}}]
        stages[st] = stage
    return {"stages": stages}


def render(root: Path = ROOT) -> dict[str, str]:
    params = build_params(root)
    dump = lambda d: HEADER + yaml.safe_dump(d, sort_keys=False, default_flow_style=False)  # noqa: E731
    return {"dvc.yaml": dump(build_dvc(params)), "params.yaml": dump(params)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if committed files are stale")
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    files = render(args.root)
    stale = [
        n
        for n, text in files.items()
        if not (args.root / n).exists() or (args.root / n).read_text() != text
    ]
    if args.check:
        if stale:
            print(f"stale: {', '.join(stale)}; run `make dvc-yaml`", file=sys.stderr)
            return 1
        print("dvc.yaml and params.yaml are up to date")
        return 0
    for n, text in files.items():
        (args.root / n).write_text(text)
        print(f"wrote {n}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
